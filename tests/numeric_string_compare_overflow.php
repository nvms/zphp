<?php
// two numeric strings compare as numbers, except integers that overflowed
// to the same side, which compare as text
$pairs = [
    ["9223372036854775807", "9223372036854775808"],
    ["-9223372036854775808", "-9223372036854775809"],
    ["9223372036854775808", "9223372036854775808"],
    ["999223372036854775807", "999223372036854775808"],
    ["899223372036854775807", "00999223372036854775807"],
    ["9223372036854775808", "1e100"],
    ["9223372036854775807", "9.2233720368547758E18"],
    ["1", "01"],
    ["10", "1e1"],
    ["1.0", "1"],
    [" 1", "1 "],
    ["abc", "1"],
    ["100", "99"],
    ["1e1000", "2e1000"],
    ["-1e1000", "-2e1000"],
    ["123", "123abc"],
];
foreach ($pairs as [$a, $b]) {
    echo $a, " vs ", $b, ": ";
    var_dump($a == $b, $a <=> $b, $b <=> $a, $a < $b);
}
var_dump(in_array("9223372036854775808", ["9223372036854775807"]));
